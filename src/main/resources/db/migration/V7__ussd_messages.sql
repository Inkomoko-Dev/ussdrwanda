-- USSD/SMS text overrides edited in the admin portal (defaults ship in i18n/ussd_*.properties).
-- Resolution at runtime: override(active country, language) -> override('*', language)
--                        -> bundle(language) -> bundle(English).
CREATE TABLE ussd_message (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    msg_key       VARCHAR(80)   NOT NULL,
    language      VARCHAR(20)   NOT NULL,              -- ELanguage name
    country_code  VARCHAR(2)    NOT NULL DEFAULT '*',  -- country_config.code, or '*' = every country
    text          VARCHAR(1000) NOT NULL,
    updated_by    VARCHAR(120)  NOT NULL,
    updated_at    TIMESTAMP     NOT NULL,
    CONSTRAINT uq_ussd_message UNIQUE (msg_key, language, country_code)
);

-- Every change, kept forever (who changed what, from what, to what).
CREATE TABLE ussd_message_history (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    msg_key       VARCHAR(80)   NOT NULL,
    language      VARCHAR(20)   NOT NULL,
    country_code  VARCHAR(2)    NOT NULL,
    action        VARCHAR(10)   NOT NULL,              -- UPDATE | REVERT
    old_text      VARCHAR(1000),                       -- NULL = was the shipped default
    new_text      VARCHAR(1000),                       -- NULL = reverted to the shipped default
    changed_by    VARCHAR(120)  NOT NULL,
    changed_at    TIMESTAMP     NOT NULL
);
CREATE INDEX idx_ussd_message_history_key ON ussd_message_history (msg_key, changed_at DESC);

-- Privileges for the "USSD texts" page (Super Administrator has every privilege already).
INSERT INTO admin_role_privilege (role_id, privilege)
SELECT r.id, p.privilege FROM admin_role r
JOIN (VALUES
  ('Operations Officer', 'MESSAGE_VIEW'), ('Operations Officer', 'MESSAGE_MANAGE'),
  ('Support Agent', 'MESSAGE_VIEW'),
  ('Viewer', 'MESSAGE_VIEW')
) AS p(role_name, privilege) ON p.role_name = r.name
ON CONFLICT DO NOTHING;
