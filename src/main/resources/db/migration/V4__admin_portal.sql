-- ── Password policy (single row) ─────────────────────────────────────────────
CREATE TABLE password_policy (
    id                   INTEGER PRIMARY KEY CHECK (id = 1),
    min_length           INTEGER NOT NULL,
    require_upper        BOOLEAN NOT NULL,
    require_lower        BOOLEAN NOT NULL,
    require_digit        BOOLEAN NOT NULL,
    require_special      BOOLEAN NOT NULL,
    expiry_days          INTEGER NOT NULL,      -- 0 = never expires
    history_count        INTEGER NOT NULL,      -- last N passwords cannot be reused
    max_failed_attempts  INTEGER NOT NULL,
    lockout_minutes      INTEGER NOT NULL,
    session_minutes      INTEGER NOT NULL,      -- JWT lifetime
    updated_at           TIMESTAMP,
    updated_by           VARCHAR(60)
);
