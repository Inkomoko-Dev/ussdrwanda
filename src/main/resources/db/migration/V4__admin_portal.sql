-- ── Roles & privileges ───────────────────────────────────────────────────────
CREATE TABLE admin_role (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR(60)  NOT NULL UNIQUE,
    description  VARCHAR(255),
    system_role  BOOLEAN      NOT NULL DEFAULT FALSE,   -- system role = all privileges, not editable
    created_at   TIMESTAMP    NOT NULL,
    updated_at   TIMESTAMP
);

CREATE TABLE admin_role_privilege (
    role_id    BIGINT      NOT NULL REFERENCES admin_role (id) ON DELETE CASCADE,
    privilege  VARCHAR(50) NOT NULL,
    PRIMARY KEY (role_id, privilege)
);

