-- Admin portal: country profiles, password policy, roles & privileges, portal users,
-- customer onboarding metadata.

-- ── Country profiles (chosen and customised in the first-run setup wizard) ──
CREATE TABLE country_config (
    code                    VARCHAR(2)    PRIMARY KEY,
    name                    VARCHAR(80)   NOT NULL,
    dial_code               VARCHAR(5)    NOT NULL,
    national_number_length  INTEGER       NOT NULL,
    currency                VARCHAR(3)    NOT NULL,
    timezone                VARCHAR(40)   NOT NULL,
    languages               VARCHAR(100)  NOT NULL,   -- ordered, comma-separated ELanguage names
    mobile_networks         VARCHAR(200),
    helpline                VARCHAR(40),
    min_repayment           NUMERIC(19,2) NOT NULL,
    max_repayment           NUMERIC(19,2) NOT NULL,
    self_registration       BOOLEAN       NOT NULL DEFAULT TRUE,
    active                  BOOLEAN       NOT NULL DEFAULT FALSE,
    created_at              TIMESTAMP     NOT NULL,
    updated_at              TIMESTAMP
);
-- Exactly one country drives the USSD service of a deployment.
CREATE UNIQUE INDEX uq_country_single_active ON country_config (active) WHERE active;

