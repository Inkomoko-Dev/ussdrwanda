-- ── Portal users ─────────────────────────────────────────────────────────────
CREATE TABLE admin_user (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username              VARCHAR(60)  NOT NULL UNIQUE,
    full_name             VARCHAR(120) NOT NULL,
    email                 VARCHAR(120),
    phone                 VARCHAR(20),
    password_hash         VARCHAR(100) NOT NULL,
    role_id               BIGINT       NOT NULL REFERENCES admin_role (id),
    country_code          VARCHAR(2)   REFERENCES country_config (code),
    status                VARCHAR(20)  NOT NULL,           -- ACTIVE | DISABLED
    failed_attempts       INTEGER      NOT NULL DEFAULT 0,
    locked_until          TIMESTAMP,
    must_change_password  BOOLEAN      NOT NULL DEFAULT TRUE,
    password_changed_at   TIMESTAMP,
    last_login_at         TIMESTAMP,
    created_by            VARCHAR(60),
    created_at            TIMESTAMP    NOT NULL,
    updated_at            TIMESTAMP
);

CREATE TABLE admin_password_history (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT       NOT NULL REFERENCES admin_user (id) ON DELETE CASCADE,
    password_hash  VARCHAR(100) NOT NULL,
    created_at     TIMESTAMP    NOT NULL
);
CREATE INDEX idx_pwd_history_user ON admin_password_history (user_id, created_at);

