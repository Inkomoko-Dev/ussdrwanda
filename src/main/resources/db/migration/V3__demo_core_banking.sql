-- Demo core banking (used when inkomoko.fineract.mode=demo, i.e. the *662*105# pilot).
-- Stands in for Fineract until the live integration is switched on with *311#.
-- Managed at runtime via /api/admin/demo/** ; ignored entirely in live mode.

CREATE TABLE demo_client (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    msisdn        VARCHAR(20)  NOT NULL UNIQUE,
    display_name  VARCHAR(150) NOT NULL,
    active        BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMP    NOT NULL,
    updated_at    TIMESTAMP
);

CREATE TABLE demo_loan (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id              BIGINT        NOT NULL REFERENCES demo_client (id) ON DELETE CASCADE,
    account_no             VARCHAR(50)   NOT NULL UNIQUE,
    product_name           VARCHAR(100)  NOT NULL,
    status                 VARCHAR(20)   NOT NULL,
    principal_outstanding  NUMERIC(19,2) NOT NULL DEFAULT 0,
    interest_outstanding   NUMERIC(19,2) NOT NULL DEFAULT 0,
    total_overdue          NUMERIC(19,2) NOT NULL DEFAULT 0,
    installment            NUMERIC(19,2) NOT NULL DEFAULT 0,
    next_due_date          DATE,
    created_at             TIMESTAMP     NOT NULL,
    updated_at             TIMESTAMP
);
CREATE INDEX idx_demo_loan_client ON demo_loan (client_id);

CREATE TABLE demo_repayment (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    loan_id     BIGINT        NOT NULL REFERENCES demo_loan (id) ON DELETE CASCADE,
    txn_date    DATE          NOT NULL,
    amount      NUMERIC(19,2) NOT NULL,
    reference   VARCHAR(60)   NOT NULL,
    created_at  TIMESTAMP     NOT NULL,
    CONSTRAINT uq_demo_repayment_ref UNIQUE (loan_id, reference)
);
CREATE INDEX idx_demo_repayment_loan ON demo_repayment (loan_id, txn_date);

