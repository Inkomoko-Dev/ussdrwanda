-- Inkomoko USSD platform (*311#) — initial schema

CREATE TABLE ussd_session (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id             VARCHAR(64)   NOT NULL,
    msisdn                 VARCHAR(20)   NOT NULL,
    gw_ref                 VARCHAR(100),
    app_ref                VARCHAR(64),
    network_code           VARCHAR(30),
    level                  INTEGER       NOT NULL DEFAULT 0,
    service                VARCHAR(30),
    step                   VARCHAR(30),
    language               VARCHAR(20),
    client_state           VARCHAR(20),
    client_id              BIGINT,
    client_name            VARCHAR(150),
    consent_accepted       BOOLEAN       NOT NULL DEFAULT FALSE,
    authenticated          BOOLEAN       NOT NULL DEFAULT FALSE,
    pending_pin_hash       VARCHAR(100),
    loan_id                BIGINT,
    loan_account_no        VARCHAR(50),
    loan_options           VARCHAR(255),
    amount                 NUMERIC(19,2),
    outstanding            NUMERIC(19,2),
    telecom                VARCHAR(10),
    processed_inputs       INTEGER       NOT NULL DEFAULT 0,
    last_raw_input         VARCHAR(200),
    last_response          VARCHAR(1000),
    last_continue_session  INTEGER,
    close_current_session  BOOLEAN       NOT NULL DEFAULT FALSE,
    end_reason             VARCHAR(30),
    request_count          INTEGER       NOT NULL DEFAULT 0,
    total_processing_ms    BIGINT        NOT NULL DEFAULT 0,
    created_at             TIMESTAMP     NOT NULL,
    updated_at             TIMESTAMP,
    ended_at               TIMESTAMP,
    CONSTRAINT uq_ussd_session UNIQUE (session_id, msisdn)
);
CREATE INDEX idx_ussd_session_msisdn     ON ussd_session (msisdn);
CREATE INDEX idx_ussd_session_created_at ON ussd_session (created_at);
CREATE INDEX idx_ussd_session_open       ON ussd_session (close_current_session, updated_at);

CREATE TABLE language_setting (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    msisdn      VARCHAR(20) NOT NULL UNIQUE,
    language    VARCHAR(20) NOT NULL,
    updated_at  TIMESTAMP
);

CREATE TABLE account_attempt (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    msisdn      VARCHAR(20) NOT NULL UNIQUE,
    attempts    INTEGER     NOT NULL DEFAULT 0,
    created_at  TIMESTAMP,
    updated_at  TIMESTAMP
);

CREATE TABLE client_pin (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    msisdn         VARCHAR(20)  NOT NULL UNIQUE,
    client_id      BIGINT,
    pin_hash       VARCHAR(100),
    status         VARCHAR(20)  NOT NULL,
    created_at     TIMESTAMP,
    updated_at     TIMESTAMP,
    locked_at      TIMESTAMP,
    last_login_at  TIMESTAMP
);
CREATE INDEX idx_client_pin_client ON client_pin (client_id);

CREATE TABLE consent_log (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    msisdn          VARCHAR(20)  NOT NULL,
    session_id      VARCHAR(64)  NOT NULL,
    accepted        BOOLEAN      NOT NULL,
    notice_version  VARCHAR(20),
    created_at      TIMESTAMP    NOT NULL
);
CREATE INDEX idx_consent_msisdn ON consent_log (msisdn);

CREATE TABLE repayment_transaction (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference         VARCHAR(40)   NOT NULL UNIQUE,
    session_id        VARCHAR(64),
    msisdn            VARCHAR(20)   NOT NULL,
    client_id         BIGINT,
    loan_id           BIGINT        NOT NULL,
    loan_account_no   VARCHAR(50),
    amount            NUMERIC(19,2) NOT NULL,
    currency          VARCHAR(5)    NOT NULL,
    telecom           VARCHAR(10),
    status            VARCHAR(20)   NOT NULL,
    gateway_ref       VARCHAR(100),
    telecom_ref       VARCHAR(100),
    fineract_txn_id   VARCHAR(50),
    posting_attempts  INTEGER       NOT NULL DEFAULT 0,
    failure_reason    VARCHAR(500),
    balance_after     NUMERIC(19,2),
    confirmed_at      TIMESTAMP,
    created_at        TIMESTAMP     NOT NULL,
    updated_at        TIMESTAMP,
    paid_at           TIMESTAMP,
    posted_at         TIMESTAMP
);
CREATE INDEX idx_repayment_status     ON repayment_transaction (status, updated_at);
CREATE INDEX idx_repayment_msisdn     ON repayment_transaction (msisdn, created_at);
CREATE INDEX idx_repayment_created_at ON repayment_transaction (created_at);

CREATE TABLE reconciliation_action (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_reference  VARCHAR(40)  NOT NULL REFERENCES repayment_transaction (reference),
    action                 VARCHAR(20)  NOT NULL,
    status                 VARCHAR(20)  NOT NULL,
    maker                  VARCHAR(100) NOT NULL,
    maker_comment          VARCHAR(500),
    checker                VARCHAR(100),
    checker_comment        VARCHAR(500),
    fineract_txn_id        VARCHAR(50),
    result                 VARCHAR(500),
    created_at             TIMESTAMP    NOT NULL,
    decided_at             TIMESTAMP
);
CREATE INDEX idx_recon_status ON reconciliation_action (status);

CREATE TABLE audit_log (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor       VARCHAR(100) NOT NULL,
    channel     VARCHAR(10)  NOT NULL,
    action      VARCHAR(60)  NOT NULL,
    resource    VARCHAR(100),
    session_id  VARCHAR(64),
    success     BOOLEAN      NOT NULL,
    detail      VARCHAR(500),
    logged_at   TIMESTAMP    NOT NULL
);
CREATE INDEX idx_audit_actor     ON audit_log (actor);
CREATE INDEX idx_audit_action    ON audit_log (action);
CREATE INDEX idx_audit_logged_at ON audit_log (logged_at);

-- Audit records are immutable: block UPDATE and DELETE at the database level.
CREATE OR REPLACE FUNCTION audit_log_immutable() RETURNS TRIGGER AS $$
BEGIN
    RAISE EXCEPTION 'audit_log is append-only';
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_audit_log_immutable
    BEFORE UPDATE OR DELETE ON audit_log
    FOR EACH ROW EXECUTE FUNCTION audit_log_immutable();

CREATE TABLE faq_item (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    language       VARCHAR(20)  NOT NULL,
    title          VARCHAR(40)  NOT NULL,
    body           VARCHAR(300) NOT NULL,
    display_order  INTEGER      NOT NULL DEFAULT 0,
    active         BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at     TIMESTAMP,
    updated_at     TIMESTAMP
);
CREATE INDEX idx_faq_lang ON faq_item (language, active, display_order);
